import argparse
import json

import src.core.database.models  # noqa: F401

from src.core.database.session import (
    SessionLocal,
)
from src.domains.matching.ml.feature_sets import (
    get_feature_set,
)
from src.domains.matching.ml.match_training_dataset_exporter import (
    MatchTrainingDatasetExporter,
)
from src.domains.matching.ml.training_dataset_manifest import (
    TrainingDatasetManifestBuilder,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Export labeled CareerAI match data "
            "as an ML training dataset."
        )
    )

    parser.add_argument(
        "--output",
        default=(
            "datasets/matching/"
            "training_v1.csv"
        ),
        help=(
            "Output path for the generated "
            "training dataset."
        ),
    )

    parser.add_argument(
        "--format",
        choices=[
            "csv",
            "jsonl",
        ],
        default="csv",
        help=(
            "Training dataset output format."
        ),
    )

    parser.add_argument(
        "--dataset-name",
        default=(
            "careerai-match-training"
        ),
        help=(
            "Logical name of the training dataset."
        ),
    )

    parser.add_argument(
        "--dataset-version",
        default="v1",
        help=(
            "Version of the generated dataset."
        ),
    )

    parser.add_argument(
        "--algorithm-version",
        default=None,
        help=(
            "Optionally export only matches "
            "generated by this algorithm version."
        ),
    )

    parser.add_argument(
        "--feature-set",
        default=(
            "match-ranking-baseline:"
            "v1-without-match-score"
        ),
        help=(
            "Registered feature set identifier."
        ),
    )

    parser.add_argument(
        "--manifest-output",
        default=None,
        help=(
            "Optional path for the generated "
            "dataset manifest. Defaults to "
            "'<output>.manifest.json'."
        ),
    )

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    feature_set = get_feature_set(
        args.feature_set,
    )

    db = SessionLocal()

    try:
        exporter = (
            MatchTrainingDatasetExporter(
                db,
            )
        )

        if args.format == "jsonl":
            metadata = exporter.export_jsonl(
                output_path=args.output,
                dataset_name=args.dataset_name,
                dataset_version=(
                    args.dataset_version
                ),
                feature_set=feature_set,
                algorithm_version=(
                    args.algorithm_version
                ),
            )

        else:
            metadata = exporter.export_csv(
                output_path=args.output,
                dataset_name=args.dataset_name,
                dataset_version=(
                    args.dataset_version
                ),
                feature_set=feature_set,
                algorithm_version=(
                    args.algorithm_version
                ),
            )

        manifest_path = (
            args.manifest_output
            or f"{args.output}.manifest.json"
        )

        manifest_builder = (
            TrainingDatasetManifestBuilder()
        )

        manifest = manifest_builder.build(
            dataset_name=args.dataset_name,
            dataset_version=(
                args.dataset_version
            ),
            dataset_path=args.output,
            dataset_format=args.format,
            feature_set=feature_set,
            algorithm_version=(
                args.algorithm_version
            ),
            row_count=metadata[
                "example_count"
            ],
            label_distribution=metadata[
                "label_distribution"
            ],
        )

        manifest_builder.save(
            manifest=manifest,
            manifest_path=manifest_path,
        )

        output = {
            **metadata,
            "manifest_path": manifest_path,
            "dataset_sha256": (
                manifest.dataset_sha256
            ),
        }

        print(
            json.dumps(
                output,
                indent=2,
                ensure_ascii=False,
            )
        )

    except Exception:
        db.rollback()
        raise

    finally:
        db.close()


if __name__ == "__main__":
    main()